export const LANGS = [
  { id: "en", label: "English" },
  { id: "fr", label: "Français" },
  { id: "zh", label: "中文" },
  { id: "ur", label: "اردو" },
  { id: "hi", label: "हिन्दी" },
  { id: "pa", label: "ਪੰਜਾਬੀ" },
] as const;

export type LangId = (typeof LANGS)[number]["id"];

const STR: Record<LangId, Pack> = { en, fr, zh, ur, hi, pa };

export function isLang(value: string): value is LangId {
  return LANGS.some((lang) => lang.id === value);
}

export function t(lang: string, key: string, vars?: Record<string, string>) {
  const pack = STR[(isLang(lang) ? lang : "en") as LangId];
  let text = (pack as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, () => value);
  }
  return text;
}
